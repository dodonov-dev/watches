// Host side of tools/gen_rod_rays.py: the edge shade's ray tables (rod.h rodRays) of one build, printed as a header.
// Built with the build's -D flags (canvas, tube widths, tube count) and -ffp-contract=off; double square roots and
// divisions are exact roundings on the host as on the board, so the tables are the ones the board would build.
#include <cstdio>
#include "rod.h"
static RodRays tab[TUBE_COUNT];
static void floats(const float *v) {
  printf("{");
  for (int i = 0; i < ROD_RAYS; i++) printf("%s%a", i ? "," : "", (double)v[i]);
  printf("}");
}
static void shorts(const int16_t *v) {
  printf("{");
  for (int i = 0; i < ROD_RAYS; i++) printf("%s%d", i ? "," : "", (int)v[i]);
  printf("}");
}
int main() {
  double R[TUBE_COUNT]; int of[TUBE_COUNT], n = 0;
  const double pitch = shadePitch();
  for (int i = 0; i < TUBE_COUNT; i++) {
    const double r = TUBE_ROD_MM(i) / 2;
    int k = 0;
    while (k < n && R[k] != r) k++;
    if (k == n) { R[n] = r; rodRays(r, ROD_GAP_MM, ROD_N, pitch, tab[n]); n++; }
    of[i] = k;
  }
  printf("// Generated by tools/gen_rod_rays.py (pre-build): the edge shade's ray tables of this build, one per distinct rod.\n");
  printf("#pragma once\n#define ROD_GEN_N %d\n", n);
  printf("static const double ROD_GEN_PITCH = %a;\n", pitch);
  printf("static const double ROD_GEN_R[ROD_GEN_N] = {");
  for (int k = 0; k < n; k++) printf("%s%a", k ? "," : "", R[k]);
  printf("};\nstatic const uint8_t ROD_GEN_OF[%d] = {", TUBE_COUNT);
  for (int i = 0; i < TUBE_COUNT; i++) printf("%s%d", i ? "," : "", of[i]);
  printf("};\nstatic const RodRays ROD_GEN[ROD_GEN_N] = {\n");
  for (int k = 0; k < n; k++) {
    printf("{"); floats(tab[k].r); printf(",\n"); floats(tab[k].tau); printf(",\n"); floats(tab[k].tau2); printf(",\n{");
    shorts(tab[k].j[0]); printf(",\n"); shorts(tab[k].j[1]); printf("}}%s\n", k + 1 < n ? "," : "");
  }
  printf("};\n");
  return 0;
}
