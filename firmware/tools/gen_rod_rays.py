"""The edge shade's ray tables of a build, generated on the build host into a header (rod_rays_gen.h: ROD_GEN, const,
so in flash; render.cpp uses them with -DROD_RAYS_GEN instead of building them in PSRAM at boot).

PlatformIO pre-script (platformio.ini extra_scripts): compiles tools/gen_rod_rays.cpp with the build's -D flags,
writes $BUILD_DIR/rodgen/rod_rays_gen.h (only when it changed) and adds -DROD_RAYS_GEN and that include path.
Host tools: generate(defines, out_dir) with the -D flags of their own build (tools/check_shade_rows.py).

The sim's copy of the edge end counts (rod.h rodEndCounts): python3 firmware/tools/gen_rod_rays.py --sim [--check]
writes sim/src/rodEndGen.ts, every rod the sim can show at 1e-6 mm (the AMOLED's 6 mm at its pitch; the LCD at 240 / 256 /
288 / 320 rows: narrow, wide and 3 .. 10 mm in 0.5 mm steps), each parity's nonzero run; --check: the checked-in file
must equal a fresh generation (exit 1 otherwise). Other rods are counted by the sim on first use.
"""
import os, subprocess, sys, tempfile
from pathlib import Path
try:
    FW = Path(__file__).resolve().parents[1]
except NameError:   # run by SCons (exec without __file__): from the project dir
    FW = Path(os.getcwd()).resolve()

def generate(defines, out_dir):
    """defines: ['-DNAME', '-DNAME=V', ...]; writes out_dir/rod_rays_gen.h, returns its path."""
    out_dir = Path(out_dir); out_dir.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix='rodgen-') as t:
        exe = Path(t) / 'gen'
        subprocess.run([os.environ.get('CXX', 'c++'), '-std=c++17', '-O2', '-ffp-contract=off', *defines,
                        '-I', str(FW / 'src'), '-I', str(FW.parent / 'spec'), str(FW / 'tools' / 'gen_rod_rays.cpp'), '-o', str(exe)], check=True)
        text = subprocess.run([str(exe)], check=True, capture_output=True, text=True).stdout
    out = out_dir / 'rod_rays_gen.h'
    if not out.exists() or out.read_text() != text: out.write_text(text)
    return out

SIM_SRC = r'''
#include <cstdio>
#include "rod.h"
#define GEN_GROUPS 256   // render.ts ROD_END_GEN_GROUPS: past every board's ROD_GROUPS (<= 137)
static uint32_t c[2][GEN_GROUPS];
static long long done[64][2]; static int nd = 0;
static void emit(double R, double pitch) {
  const long long kr = (long long)floor(R * 1e6 + 0.5), kp = (long long)floor(pitch * 1e6 + 0.5);
  for (int i = 0; i < nd; i++) if (done[i][0] == kr && done[i][1] == kp) return;
  done[nd][0] = kr; done[nd][1] = kp; nd++;
  rodEndCounts(R, ROD_GAP_MM, ROD_N, pitch, c[0], c[1], GEN_GROUPS);
  printf("  [%lld, %lld", kr, kp);
  for (int q = 0; q < 2; q++) {
    int a = 0, b = GEN_GROUPS; while (a < b && !c[q][a]) a++; while (b > a && !c[q][b - 1]) b--;
    printf(", [%d", a); for (int j = a; j < b; j++) printf(", %u", (unsigned)c[q][j]); printf("]");
  }
  printf("],\n");
}
int main() {
  emit(3.0, (double)240 / 240 / (double)(1.0f / 0.083f));   // the AMOLED (layout.h PX_PER_MM, shadePitch)
  const int rows[4] = {240, 256, 288, 320};
  for (int r : rows) {   // layout.h PX_SCALE_NARROW / _WIDE / _MM, TUBE_ROD_MM, PX_PER_MM, shadePitch at RENDER_H r
    const float narrow = (float)((double)0.083f * r / ((double)0.0825f * 320)), wide = (float)r / 240;
    const float pxmm = narrow / 0.083f; const double pitch = (double)r / 320 / (double)pxmm;
    emit(6.0 * (double)narrow / (double)narrow / 2, pitch); emit(6.0 * (double)wide / (double)narrow / 2, pitch);
    for (int h = 6; h <= 20; h++) { const float k = narrow * ((float)(h * 0.5) / 6.0f); emit(6.0 * (double)k / (double)narrow / 2, pitch); }
  }
  return 0;
}
'''

def generate_sim(check=False):
    """sim/src/rodEndGen.ts (rod.h rodEndCounts for the sim's rods); check: compare instead of writing."""
    with tempfile.TemporaryDirectory(prefix='rodend-') as t:
        src, exe = Path(t) / 'g.cpp', Path(t) / 'g'
        src.write_text(SIM_SRC)
        subprocess.run([os.environ.get('CXX', 'c++'), '-std=c++17', '-O2', '-ffp-contract=off', '-DBOARD_LCD316',
                        '-I', str(FW / 'src'), '-I', str(FW.parent / 'spec'), str(src), '-o', str(exe)], check=True)
        rows = subprocess.run([str(exe)], check=True, capture_output=True, text=True).stdout
    text = ('// GENERATED by firmware/tools/gen_rod_rays.py --sim — do not edit. The edge end counts (firmware rod.h rodEndCounts,\n'
            '// render.ts rodEndCounts) of the rods the sim can show: [R, pitch] in 1e-6 mm, then per parity (even, odd) [first\n'
            '// group, its counts ...] of the nonzero run; every other group 0. Groups from ROD_END_GEN_GROUPS on are dropped.\n'
            'export const ROD_END_GEN_GROUPS = 256;\n'
            'export const ROD_END_GEN: readonly (readonly [number, number, readonly number[], readonly number[]])[] = [\n' + rows + '];\n')
    out = FW.parent / 'sim' / 'src' / 'rodEndGen.ts'
    if check:
        ok = out.exists() and out.read_text() == text
        print('rodEndGen.ts ' + ('up to date' if ok else 'differs from a fresh generation')); return ok
    out.write_text(text); print('wrote', out); return True

def _pio():
    Import("env")  # noqa: F821 (SCons)
    # the defines exactly as PlatformIO parses build_flags (PLATFORMIO_BUILD_FLAGS included), in order: a repeated name
    # resolves as in the firmware's own compile (the last one wins)
    parsed = env.ParseFlagsExtended(env.get("BUILD_FLAGS", []))  # noqa: F821
    defines = []
    for d in parsed.get("CPPDEFINES", []):
        if isinstance(d, (tuple, list)): defines.append("-D%s=%s" % (d[0], env.subst(str(d[1]))))  # noqa: F821
        else: defines.append("-D%s" % d)
    out_dir = Path(env.subst("$BUILD_DIR")) / "rodgen"  # noqa: F821
    try:
        generate(defines, out_dir)
    except subprocess.CalledProcessError as e:
        sys.stderr.write("gen_rod_rays: the host generator failed (%s)\n" % e)
        env.Exit(1)  # noqa: F821
    env.Append(CPPPATH=[str(out_dir)], CPPDEFINES=["ROD_RAYS_GEN"])  # noqa: F821

if __name__ == '__main__':
    if '--sim' not in sys.argv[1:]: sys.exit('usage: gen_rod_rays.py --sim [--check] (the pre-build runs it inside PlatformIO)')
    sys.exit(0 if generate_sim('--check' in sys.argv[1:]) else 1)
else:
    try:
        Import  # noqa: F821 (only defined inside SCons)
    except NameError:
        pass
    else:
        _pio()
